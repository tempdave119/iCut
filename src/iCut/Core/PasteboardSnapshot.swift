import AppKit
import CryptoKit
import ImageIO

/// 一次剪贴板变化的规范化快照：类型判定、敏感标记过滤与大小截断都在这里完成，
/// 与定时器和磁盘解耦，便于单测。
struct PasteboardSnapshot: Equatable {
    enum Kind: String, Equatable {
        case text
        case image
        case fileURLs
    }

    let kind: Kind
    let text: String?
    let rtfData: Data?
    let imagePNG: Data?
    let thumbnailPNG: Data?
    /// 原图的点尺寸比例（像素 / 点）；截图写入的图片带 scale，粘贴时才不会放大。
    let imageScale: CGFloat
    let filePaths: [String]
    let hash: Data
    let byteCount: Int
    let isTruncated: Bool

    static let maxTextBytes = 100 * 1024
    static let maxRTFBytes = 200 * 1024
    static let maxImageBytes = 20 * 1024 * 1024
    static let maxFilePaths = 20
    static let thumbnailMaxPixel = 64

    /// 敏感内容标记：密码管理器、无痕窗口等会打这些类型（约定见 nspasteboard.org）。
    /// 只要出现任一标记就整条丢弃，不做部分解析。
    static let concealedTypes: [NSPasteboard.PasteboardType] = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("com.agilebits.onepassword")
    ]

    static func parse(_ pasteboard: NSPasteboard, recordImages: Bool) -> PasteboardSnapshot? {
        let types = pasteboard.types ?? []
        if types.contains(where: concealedTypes.contains) { return nil }

        // 文件复制时系统同时提供路径字符串，必须先按文件解析
        if let snapshot = readFileURLs(pasteboard) { return snapshot }
        if recordImages, let snapshot = readImage(pasteboard) { return snapshot }
        if let snapshot = readText(pasteboard) { return snapshot }
        return nil
    }

    private static func readFileURLs(_ pasteboard: NSPasteboard) -> PasteboardSnapshot? {
        guard let objects = pasteboard.readObjects(
            forClasses: [NSURL.self],
            options: [.urlReadingFileURLsOnly: true]
        ) else { return nil }

        let urls = objects.compactMap { $0 as? URL }
        guard !urls.isEmpty else { return nil }

        let paths = urls.prefix(maxFilePaths).map(\.path)
        let joined = paths.joined(separator: "\n")
        return PasteboardSnapshot(
            kind: .fileURLs,
            text: nil,
            rtfData: nil,
            imagePNG: nil,
            thumbnailPNG: nil,
            imageScale: 1,
            filePaths: paths,
            hash: sha256(Data(joined.utf8)),
            byteCount: joined.utf8.count,
            isTruncated: urls.count > maxFilePaths
        )
    }

    private static func readImage(_ pasteboard: NSPasteboard) -> PasteboardSnapshot? {
        let tiff = pasteboard.data(forType: .tiff)
        var png = pasteboard.data(forType: .png)
        if png == nil, let tiff {
            png = pngData(fromTIFF: tiff)
        }
        guard let imagePNG = png, imagePNG.count <= maxImageBytes else { return nil }

        return PasteboardSnapshot(
            kind: .image,
            text: nil,
            rtfData: nil,
            imagePNG: imagePNG,
            thumbnailPNG: thumbnail(from: imagePNG),
            imageScale: imageScale(tiff: tiff, png: imagePNG),
            filePaths: [],
            hash: sha256(imagePNG),
            byteCount: imagePNG.count,
            isTruncated: false
        )
    }

    /// TIFF 保留了点尺寸，优先用它推 scale；只有 PNG 时退化为按像素处理。
    private static func imageScale(tiff: Data?, png: Data) -> CGFloat {
        for data in [tiff, png].compactMap({ $0 }) {
            guard let rep = NSBitmapImageRep(data: data),
                  rep.pixelsWide > 0,
                  rep.size.width > 0 else { continue }
            let scale = CGFloat(rep.pixelsWide) / rep.size.width
            if scale > 0 { return scale }
        }
        return 1
    }

    private static func readText(_ pasteboard: NSPasteboard) -> PasteboardSnapshot? {
        guard let raw = pasteboard.string(forType: .string), !raw.isEmpty else { return nil }

        let data = Data(raw.utf8)
        let truncated = data.count > maxTextBytes
        // 按字节截断可能切断多字节字符，String(decoding:) 会把坏字节替换成 U+FFFD
        let text = truncated ? String(decoding: data.prefix(maxTextBytes), as: UTF8.self) : raw
        let rtf = pasteboard.data(forType: .rtf).flatMap { $0.count <= maxRTFBytes ? $0 : nil }

        return PasteboardSnapshot(
            kind: .text,
            text: text,
            rtfData: rtf,
            imagePNG: nil,
            thumbnailPNG: nil,
            imageScale: 1,
            filePaths: [],
            hash: sha256(Data(text.utf8)),
            byteCount: data.count,
            isTruncated: truncated
        )
    }

    private static func pngData(fromTIFF tiff: Data) -> Data? {
        guard let rep = NSBitmapImageRep(data: tiff) else { return nil }
        return rep.representation(using: .png, properties: [:])
    }

    private static func thumbnail(from png: Data) -> Data? {
        guard let source = CGImageSourceCreateWithData(png as CFData, nil) else { return nil }
        let options: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceCreateThumbnailWithTransform: true,
            kCGImageSourceThumbnailMaxPixelSize: thumbnailMaxPixel
        ]
        guard let image = CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary) else {
            return nil
        }
        return NSBitmapImageRep(cgImage: image).representation(using: .png, properties: [:])
    }

    private static func sha256(_ data: Data) -> Data {
        Data(SHA256.hash(data: data))
    }
}
